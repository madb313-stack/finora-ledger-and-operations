// ─── Translation map ─────────────────────────────────────────────────────────

const translations: Record<Locale, Translations> = { ar, en };

// ─── Helpers ─────────────────────────────────────────────────────────────────

const STORAGE_KEY = "finora-locale";

function getStoredLocale(): Locale {
  if (typeof window === "undefined") return "ar";
  const stored = localStorage.getItem(STORAGE_KEY);
  if (stored === "ar" || stored === "en") return stored;
  return "ar";
}

function resolve(obj: Translations, path: string): string {
  const parts = path.split(".");
  let current: TranslationLeaf | TranslationBranch | undefined = obj;
  for (const part of parts) {
    if (current === undefined || typeof current === "string") return path;
    current = (current as TranslationBranch)[part];
  }
  return typeof current === "string" ? current : path;
}

// ─── Context ─────────────────────────────────────────────────────────────────

const I18nContext = createContext<I18nContextValue | null>(null);

// ─── Provider ────────────────────────────────────────────────────────────────

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>(getStoredLocale);

  const setLocale = useCallback((l: Locale) => {
    setLocaleState(l);
    localStorage.setItem(STORAGE_KEY, l);
  }, []);

  const dir: Dir = locale === "ar" ? "rtl" : "ltr";
  const isRTL = locale === "ar";

  // Apply dir and lang to the <html> element
  useEffect(() => {
    const html = document.documentElement;
    html.setAttribute("dir", dir);
    html.setAttribute("lang", locale);
  }, [dir, locale]);

  const t = useCallback(
    (key: string): string => resolve(translations[locale], key),
    [locale],
  );

  const value = useMemo<I18nContextValue>(
    () => ({ locale, setLocale, dir, isRTL, t }),
    [locale, setLocale, dir, isRTL, t],
  );

  return (
    <I18nContext.Provider value={value}>{children}</I18nContext.Provider>
  );
}

// ─── Hook ────────────────────────────────────────────────────────────────────

export function useTranslation(): I18nContextValue {
  const ctx = useContext(I18nContext);
  if (!ctx) {
    throw new Error("useTranslation must be used within an I18nProvider");
  }
  return ctx;
}
